defmodule HoodrideWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :hoodride

  # The session will be stored in the cookie and signed,
  # this means its contents can be read but not tampered with.
  # Set :encryption_salt if you would also like to encrypt it.
  # Lax: sent on Google's GET redirect back (a top-level navigation), so the
  # sign-in's state and PKCE verifier survive the round trip (MDN).
  # max_age: the browser keeps it 30 days (the SERVER enforces the same
  # limit — HoodrideWeb.Auth); secure: HTTPS only, in prod.
  @session_options [
    store: :cookie,
    key: "_hoodride_key",
    signing_salt: "e4AIm8XI",
    same_site: "Lax",
    max_age: 30 * 86_400,
    secure: Application.compile_env(:hoodride, :secure_cookie, false)
  ]

  # auth_token: the app sends its socket token in the WebSocket protocol
  # header, not the URL — out of proxy access logs (UserSocket). A TOP-LEVEL
  # socket option: Phoenix copies it over the transport's own (endpoint.ex
  # put_socket_opts) — set inside `websocket:` it was silently nil, every
  # header-token connect refused (caught live; ChannelTest skips the transport)
  socket "/socket", HoodrideWeb.UserSocket,
    # peer_data + x_headers: the visitor's address for the handshake budget
    # (sockets are dispatched before this endpoint's plugs — HoodrideWeb.ClientIp)
    # max_frame_size: what the server ACCEPTS per message (default 10 MB);
    # the largest real one is a chat message, ≤ 20 KB (UserChannel). Over:
    # closed with 1009 "message too big" (WsFrameLimitTest)
    websocket: [
      connect_info: [:peer_data, :x_headers, session: @session_options],
      max_frame_size: Hoodride.Limits.ws_frame_bytes()
    ],
    longpoll: false,
    auth_token: true

  # browser protections on every answer, static files included (so: before
  # Plug.Static) — security_headers_test.exs
  plug :security_headers
  # an old page's `?vsn=` after a deploy: answered as unversioned, so the new
  # contents are never kept a year under the old address (StaticVersions)
  plug :stale_vsn

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :hoodride,
    gzip: not code_reloading?,
    only: HoodrideWeb.static_paths(),
    # off even in dev: index.html and sw.js sit in priv/static but are
    # served stamped by PageController, and this would raise on them
    # instead of passing them on. A file forgotten in static_paths is
    # caught by test/hoodride_web/static_files_test.exs instead.
    raise_on_missing_only: false,
    # versioned (`?vsn=`, the page's own addresses): Plug.Static's default,
    # a year, immutable. Anything else: kept but checked first — "public"
    # alone became 4 hours behind Cloudflare (StaticVersions)
    cache_control_for_etags: "no-cache"

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    plug Phoenix.CodeReloader
    plug Phoenix.Ecto.CheckRepoStatus, otp_app: :hoodride
  end

  plug Plug.RequestId
  # the visitor's real address behind our proxy (trusted proxies only)
  plug HoodrideWeb.ClientIp
  # request lines: on in dev, OFF in prod (`config :hoodride, :request_log`) —
  # ordinary use leaves no trace; warnings and errors still log (privacy
  # policy: technical error logs, 14 days — deploy/journald-hoodride.conf)
  plug Plug.Telemetry,
    event_prefix: [:phoenix, :endpoint],
    log: Application.compile_env(:hoodride, :request_log, :info)

  # bodies over the limit refused unread; any other non-JSON body: the
  # connection closed after the answer, so Bandit never reads its rest
  # (up to 8 MB in memory per request — HoodrideWeb.BodyGate)
  plug HoodrideWeb.BodyGate

  # ONLY small JSON (server review, 2026-11-08): forms and file uploads up
  # to 8 MB used to be read — uploads written to disk — on any address,
  # before any limit. Nothing in Hood Ride sends either. Read in pieces and
  # counted as it arrives: past 64 KB, 413 at once, the rest never read.
  # Any other type is left unread (`pass`): a forged form fills in nothing,
  # and the CSP reports' own type is read by their controller. (A form-
  # posting callback added one day — e.g. Facebook's data deletion — needs
  # its own parser on its own route.) No method override: nothing uses it.
  plug Plug.Parsers,
    parsers: [:json],
    pass: ["*/*"],
    length: Hoodride.Limits.http_body_bytes(),
    read_length: Hoodride.Limits.http_body_bytes(),
    json_decoder: Phoenix.json_library()

  plug Plug.Head
  plug Plug.Session, @session_options
  plug HoodrideWeb.Router

  defp stale_vsn(%Plug.Conn{query_string: "vsn=" <> rest} = conn, _opts) do
    [vsn | _] = String.split(rest, "&", parts: 2)

    if HoodrideWeb.StaticVersions.of(Enum.join(conn.path_info, "/")) == vsn,
      do: conn,
      else: %{conn | query_string: ""}
  end

  defp stale_vsn(conn, _opts), do: conn

  # what may load, run and be sent where (HoodrideWeb.CSP), no framing
  # (clickjacking), no type guessing, and the page address never sent to
  # other sites (map tiles, Google Maps). A photo replaces the CSP with its
  # own stricter one (AvatarController).
  defp security_headers(conn, _opts) do
    Plug.Conn.merge_resp_headers(
      conn,
      [
        {"x-frame-options", "DENY"},
        {"x-content-type-options", "nosniff"},
        {"referrer-policy", "same-origin"}
      ] ++ HoodrideWeb.CSP.headers()
    )
  end
end
